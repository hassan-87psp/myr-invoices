-- Native VPS database foundation. Isolated from any existing public tables.
-- Does not import customer data or enable application access.
BEGIN;
DO $guard$
BEGIN
  IF current_database() <> 'myrinvoice' OR current_user <> 'myrinvoice_app' THEN
    RAISE EXCEPTION 'Run only on the dedicated VPS database as myrinvoice_app';
  END IF;
END
$guard$;
CREATE SCHEMA IF NOT EXISTS myr_native;
REVOKE ALL ON SCHEMA myr_native FROM PUBLIC;
SET LOCAL search_path = myr_native, pg_catalog;
CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE CHECK (email = lower(email)),
  name text,
  password_hash text,
  email_verified_at timestamptz,
  is_platform_admin boolean NOT NULL DEFAULT false,
  disabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Imported accounts remain disabled until the migration and authentication process is validated.
CREATE TABLE IF NOT EXISTS sessions (
  token_digest bytea PRIMARY KEY CHECK (octet_length(token_digest)=32),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE TABLE IF NOT EXISTS auth_tokens (
  token_digest bytea PRIMARY KEY CHECK (octet_length(token_digest)=32),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('verify_email','reset_password')),
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);
CREATE TABLE IF NOT EXISTS companies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL DEFAULT '',
  tin text NOT NULL DEFAULT '',
  plan text NOT NULL DEFAULT 'Starter' CHECK(plan IN ('Starter','Pro','Business','Accountant','Enterprise')),
  status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','suspended')),
  version integer NOT NULL DEFAULT 1 CHECK(version>0),
  data jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(data)='object'),
  created_by uuid NOT NULL REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS company_members (
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  email text NOT NULL CHECK(email=lower(email)),
  name text,
  role text NOT NULL CHECK(role IN ('Owner','Admin','Accountant','Invoice Staff','Approver','Read-Only')),
  status text NOT NULL CHECK(status IN ('active','invited','removed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(company_id,email)
);
CREATE INDEX IF NOT EXISTS company_members_email_idx ON company_members(email);
CREATE TABLE IF NOT EXISTS lhdn_documents (
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  invoice_id text NOT NULL,
  environment text NOT NULL CHECK(environment IN ('sandbox','production')),
  code_number text, submission_uid text, uuid text, long_id text,
  status text NOT NULL, validated_at timestamptz,
  errors jsonb NOT NULL DEFAULT '[]'::jsonb,
  accepted_at timestamptz, updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(company_id,invoice_id)
);
CREATE TABLE IF NOT EXISTS lhdn_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid REFERENCES companies(id) ON DELETE CASCADE,
  kind text NOT NULL, detail text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public_links (
  token text PRIMARY KEY CHECK(length(token)>=20),
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK(kind IN ('qr','invoice')),
  ref_id text NOT NULL, expires_at date NOT NULL,
  closed boolean NOT NULL DEFAULT true,
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  data jsonb, submits integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid REFERENCES companies(id) ON DELETE SET NULL,
  actor uuid, actor_email text, action text NOT NULL, detail text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_company_idx ON audit_logs(company_id,created_at DESC);
CREATE TABLE IF NOT EXISTS company_revisions (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  version integer NOT NULL,
  data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(company_id,version)
);
REVOKE ALL ON ALL TABLES IN SCHEMA myr_native FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA myr_native FROM PUBLIC;
COMMIT;
SELECT count(*) AS native_foundation_tables FROM information_schema.tables
WHERE table_schema='myr_native' AND table_type='BASE TABLE';
\echo VPS_SCHEMA_FOUNDATION_OK
