"""Operator-run smoke test of the existing private CHIP sandbox function.
No real card, live purchase, subscription change or automatic POST retry.
The operator must independently confirm the configured key is a CHIP TEST key.
"""
import os,sys,json,re,getpass,ssl
from pathlib import Path
from uuid import UUID
from urllib.request import Request,build_opener,ProxyHandler,HTTPSHandler
from urllib.error import HTTPError
from business_lhdn import private_text,NoRedirect

URL="https://nynghaleoaqilewmhbdi.supabase.co/functions/v1/myr-chip-sandbox-checkout"
STATE=Path.home()/".config/myrinvoice/chip-manual-sandbox-state.json"
def write_state(data,exclusive=False):
    if exclusive:
        with STATE.open("x") as f:json.dump(data,f)
    else:
        temp=STATE.with_suffix(".tmp")
        with temp.open("x") as f:json.dump(data,f)
        os.replace(temp,STATE)
def uid(value):
    return str(UUID(value))
def main():
    os.umask(0o077)
    if sys.argv[1:] not in (["create"],["verify"]):raise SystemExit("Use create or verify")
    create=sys.argv[1]=="create"
    if create and STATE.exists():raise SystemExit("Existing attempt: use verify or reconcile with CHIP before any new creation.")
    if not create:
        old=json.loads(private_text(STATE.name))
        if old.get("state")!="created" and old.get("state")!="paid":raise SystemExit("Previous outcome unknown; reconcile in CHIP portal before retry.")
        payload={"action":"verify_test","intent_id":uid(old["intent_id"]),"purchase_id":uid(old["purchase_id"])}
    else:
        print("Confirm in CHIP portal that the configured API key is a TEST key, not a live key.")
        if input("Type TEST ONLY to create one simulated RM9 checkout: ").strip()!="TEST ONLY":raise SystemExit("Cancelled")
        payload={"action":"create_test","confirm":"I_VERIFIED_CHIP_TEST_KEY"}
    try:secret=private_text("chip-operator-secret").strip()
    except FileNotFoundError:secret=getpass.getpass("Existing CHIP_OPERATOR_SECRET (hidden): ").strip()
    if not re.fullmatch(r"[a-fA-F0-9]{64}",secret):raise SystemExit("Operator secret missing or wrong format. No request sent.")
    opener=build_opener(ProxyHandler({}),NoRedirect(),HTTPSHandler(context=ssl.create_default_context()))
    req=Request(URL,data=json.dumps(payload).encode(),method="POST",headers={"Content-Type":"application/json","X-Chip-Operator-Secret":secret,"Accept":"application/json"})
    if create:write_state({"state":"dispatching"},exclusive=True)
    try:
        with opener.open(req,timeout=25) as r:status=r.status;raw=r.read(8193)
    except HTTPError as e:status=e.code;raw=e.read(8193)
    except Exception:raise SystemExit("Request outcome unknown. Do not create again; check CHIP portal.")
    print("CHIP_HTTP",status)
    try:
        if len(raw)>8192:raise ValueError()
        d=json.loads(raw)
        if not isinstance(d,dict):raise ValueError()
    except ValueError:raise SystemExit("Unexpected response. Do not retry creation.")
    if status!=200:
        # These exact responses are generated by the function before a provider call.
        if create and ((status==401 and d.get("error")=="operator_only") or (status==503 and d.get("error")=="invalid_test_configuration")):
            STATE.unlink()
            raise SystemExit("Configuration rejected before purchase creation. Correct the existing private configuration.")
        raise SystemExit("Purchase not verified. Do not retry creation; reconcile in CHIP portal.")
    if d.get("ok") is not True or d.get("is_test") is not True or d.get("amount_sen")!=900 or d.get("entitlement_changed") is not False:
        raise SystemExit("Unexpected response; no verified test payment.")
    if create:
        pid,iid=uid(d["purchase_id"]),uid(d["intent_id"])
        checkout="https://gate.chip-in.asia/p/"+pid+"/"
        if d.get("status")!="created" or d.get("checkout_url")!=checkout:raise SystemExit("Unexpected checkout; reconcile first.")
        write_state({"state":"created","purchase_id":pid,"intent_id":iid})
        print("MYR_CHIP_TEST_CHECKOUT_CREATED")
        print("Open this private checkout URL in your browser:",checkout)
        print("Use the CHIP simulated payment method only. Do not enter real card or bank details.")
    else:
        if d.get("purchase_id")!=payload["purchase_id"]:raise SystemExit("Purchase mismatch.")
        if d.get("verified_test_paid") is True and d.get("status")=="paid":
            write_state({**old,"state":"paid"})
            print("MYR_CHIP_ACTUAL_SANDBOX_PAYMENT_VERIFIED")
        else:print("MYR_CHIP_TEST_PAYMENT_NOT_YET_VERIFIED")
if __name__=="__main__":main()
